"""Tests for scripts/prepare_docs_build.py (no Django)."""

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "prepare_docs_build.py"


def _load():
    spec = importlib.util.spec_from_file_location("prepare_docs_build", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def test_use_fork_whats_new_channels():
    mod = _load()
    assert mod.use_fork_whats_new("beta") is True
    assert mod.use_fork_whats_new("local") is True
    assert mod.use_fork_whats_new("pr") is True
    assert mod.use_fork_whats_new("unknown-channel") is False


def test_fork_whats_new_body_strips_title():
    mod = _load()
    body = mod.fork_whats_new_body()
    assert body.startswith("These notes cover") or body.startswith("## Features")
    assert not body.lstrip().startswith("# ")
    assert "## Features" in body
    assert "**admin:**" in body


def test_fork_version_matches_file():
    mod = _load()
    assert mod.fork_version() == (ROOT / "version" / "FORK_VERSION").read_text(encoding="utf-8").strip()


def test_write_whats_new_beta_includes_fork_and_upstream(tmp_path, monkeypatch):
    mod = _load()
    monkeypatch.setenv("DOCS_CHANNEL", "beta")
    monkeypatch.setattr(mod, "REF", tmp_path)
    upstream = "## [9.4.0](https://example.test) (2026-10-26)\n\n### Features\n\n* upstream only\n"
    mod.write_whats_new(upstream, "9.4.0", fork_ver="10.0.0")
    text = (tmp_path / "whats-new.md").read_text(encoding="utf-8")
    assert "generated by scripts/prepare_docs_build.py" in text
    assert "fork 10.0.0" in text
    assert "## Features" in text
    assert "**admin:**" in text
    assert "## Upstream base (9.4.0)" in text
    assert "upstream only" in text


def test_write_changelog_beta_preamble(tmp_path, monkeypatch):
    mod = _load()
    monkeypatch.setenv("DOCS_CHANNEL", "beta")
    monkeypatch.setattr(mod, "REF", tmp_path)
    mod.write_changelog("# Changelog\n\n## [9.4.0]()\n\n### Features\n\n* x\n", fork_ver="10.0.0")
    text = (tmp_path / "changelog.md").read_text(encoding="utf-8")
    assert "## Fork line (10.0.0)" in text
    assert "[What's new](whats-new.md)" in text
    assert "## [9.4.0]()" in text
