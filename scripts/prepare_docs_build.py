#!/usr/bin/env python3
"""Generate version, changelog, languages, and optional OpenAPI pages before mkdocs build."""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DOCS_EN = ROOT / "docs" / "en"
REF = DOCS_EN / "reference"
GENERATED_MARKER = "<!-- generated by scripts/prepare_docs_build.py; do not edit -->"


def package_version() -> str:
    data = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    return data["version"]


def git_sha() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"


def git_tag_for_version(version: str) -> str | None:
    tag = f"v{version}"
    try:
        found = subprocess.check_output(["git", "tag", "-l", tag], cwd=ROOT, text=True).strip()
        return tag if found == tag else None
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def changelog_text() -> str:
    return (ROOT / "CHANGELOG.md").read_text(encoding="utf-8")


def release_section(changelog: str, version: str) -> tuple[str, str | None]:
    """Return (section markdown without H1, release date or None)."""
    pattern = re.compile(
        rf"^## \[{re.escape(version)}\].*?\n(.*?)(?=^## |\Z)",
        re.MULTILINE | re.DOTALL,
    )
    match = pattern.search(changelog)
    if not match:
        return f"No changelog section for {version}.\n", None
    heading = changelog[match.start() : match.start() + changelog[match.start() :].find("\n")]
    date_match = re.search(r"\((\d{4}-\d{2}-\d{2})\)", heading)
    date = date_match.group(1) if date_match else None
    body = match.group(0).strip() + "\n"
    return body, date


def docs_channel() -> str:
    return os.environ.get("DOCS_CHANNEL", "local")


def build_info_line() -> str:
    repo = os.environ.get("GITHUB_REPOSITORY")
    run_id = os.environ.get("GITHUB_RUN_ID")
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    if repo and run_id:
        url = f"https://github.com/{repo}/actions/runs/{run_id}"
        return f"{when}. [GitHub Actions run]({url})."
    return f"{when}. Local build."


def repository_slug() -> str:
    return os.environ.get("GITHUB_REPOSITORY", "mediacms-io/mediacms")


def write_this_version(version: str, release_date: str | None, tag: str | None) -> None:
    repo = repository_slug()
    tag_name = tag or f"v{version}"
    release_url = f"https://github.com/{repo}/releases/tag/{tag_name}"
    zip_url = f"https://github.com/{repo}/archive/refs/tags/{tag_name}.zip"
    tar_url = f"https://github.com/{repo}/archive/refs/tags/{tag_name}.tar.gz"
    docker_base = f"`mediacms/mediacms:{version}`"
    docker_full = f"`mediacms/mediacms:{version}-full`"
    date_line = release_date or "Unknown"
    tag_line = tag if tag else f"{tag_name} (tag not on this commit)"
    content = f"""{GENERATED_MARKER}
# This version

Identity, build, and artifact links for the documentation version you are reading.

| Field | Value |
|-------|-------|
| Version | {version} |
| Release date | {date_line} |
| Git tag | {tag_line} |
| Commit | `{git_sha()}` |
| Docs channel | `{docs_channel()}` |
| Docs build | {build_info_line()} |

## Requirements

- Python 3.11 or newer
- Django 5.2
- PostgreSQL 15 or newer (development compose uses PostgreSQL 17)
- Node 20.9.0 or newer
- License: [AGPL-3.0](https://github.com/{repo}/blob/v{version}/LICENSE.txt)

Source repository: [https://github.com/{repo}](https://github.com/{repo})

## Artifacts

Links use the release URL pattern. Items marked **placeholder** are not confirmed in this build.

| Artifact | Link |
|----------|------|
| GitHub release | [{tag_name}]({release_url}) |
| Source zip | [{tag_name}.zip]({zip_url}) (placeholder) |
| Source tar.gz | [{tag_name}.tar.gz]({tar_url}) (placeholder) |
| Docker image | {docker_base} on [Docker Hub](https://hub.docker.com/r/mediacms/mediacms) (placeholder) |
| Docker full image | {docker_full} (placeholder) |
| OpenAPI schema | [openapi.yaml](openapi.yaml) |
| Checksums | Not published yet |
| SBOM | Not published yet |

See also [What's new](whats-new.md) and [Changelog](changelog.md).
"""
    (REF / "this-version.md").write_text(content, encoding="utf-8")


def write_whats_new(section: str, version: str) -> None:
    content = f"""{GENERATED_MARKER}
# What's new

Changes in MediaCMS {version}. See [This version](this-version.md) for build and artifact details.

{section}
"""
    (REF / "whats-new.md").write_text(content, encoding="utf-8")


def write_changelog(changelog: str) -> None:
    # Drop the leading H1 so MkDocs page title stays "Changelog"
    body = re.sub(r"^# Changelog\s*", "", changelog, count=1, flags=re.MULTILINE).strip()
    content = f"""{GENERATED_MARKER}
# Changelog

Release history through the version of this documentation build.

{body}
"""
    (REF / "changelog.md").write_text(content, encoding="utf-8")


def write_languages_page() -> None:
    data = yaml.safe_load((ROOT / "docs" / "languages.yml").read_text(encoding="utf-8"))
    rows = []
    for entry in data["languages"]:
        locale = entry["locale"]
        name = entry["name"]
        published = "Yes" if entry.get("build") else "No"
        direction = "RTL" if entry.get("rtl") else "LTR"
        if entry.get("default"):
            link = f"[Home](../index.md)"
        elif entry.get("build"):
            link = f"`/{locale}/`"
        else:
            link = "—"
        rows.append(f"| `{locale}` | {name} | {direction} | {published} | {link} |")
    table = "\n".join(rows)
    content = f"""{GENERATED_MARKER}
# Languages

MediaCMS documentation can ship in more than one language. English is the default. Other languages appear here when they are published.

| Locale | Name | Direction | Published | Open |
|--------|------|-----------|-----------|------|
{table}

## Add a language

1. Run `python scripts/add_docs_language.py <locale>`.
2. Translate pages under `docs/<locale>/`.
3. Leave UI labels in bold as the English words on the product screen.
4. Rebuild the site.

Untranslated pages fall back to English with a short notice.
"""
    (DOCS_EN / "languages.md").write_text(content, encoding="utf-8")


def ensure_openapi_stub() -> None:
    path = REF / "openapi.yaml"
    if path.exists():
        return
    path.write_text(
        """openapi: 3.0.3
info:
  title: MediaCMS API
  version: v1
  description: >
    Schema placeholder. Replace this file in CI with
    `python manage.py generate_swagger --format yaml`.
paths: {}
""",
        encoding="utf-8",
    )


def write_api_page() -> None:
    content = f"""{GENERATED_MARKER}
# REST API

OpenAPI schema for this documentation version. The live portal also serves Swagger at `/swagger/` and ReDoc at `/docs/api/`.

Download the schema: [openapi.yaml](openapi.yaml)

```swagger
openapi.yaml
```
"""
    (REF / "api.md").write_text(content, encoding="utf-8")


def copy_shared_assets() -> None:
    """Copy shared styles and assets into each locale that will build."""
    import shutil

    # Keep shared files under docs/_shared so exclude_docs never matches
    # Material theme files that also live under site/assets/.
    shared = [
        (ROOT / "docs" / "_shared" / "stylesheets", "stylesheets"),
        (ROOT / "docs" / "_shared" / "assets", "assets"),
    ]
    data = yaml.safe_load((ROOT / "docs" / "languages.yml").read_text(encoding="utf-8"))
    locales = [item["locale"] for item in data["languages"] if item.get("build")]
    if "en" not in locales:
        locales.append("en")
    for locale in locales:
        for source, name in shared:
            if not source.is_dir():
                continue
            dest = ROOT / "docs" / locale / name
            dest.mkdir(parents=True, exist_ok=True)
            for path in source.iterdir():
                target = dest / path.name
                if path.is_file():
                    shutil.copy2(path, target)


def main() -> int:
    REF.mkdir(parents=True, exist_ok=True)
    version = package_version()
    changelog = changelog_text()
    section, release_date = release_section(changelog, version)
    tag = git_tag_for_version(version)
    write_this_version(version, release_date, tag)
    write_whats_new(section, version)
    write_changelog(changelog)
    write_languages_page()
    ensure_openapi_stub()
    write_api_page()
    copy_shared_assets()
    print(f"Prepared docs for version {version}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
